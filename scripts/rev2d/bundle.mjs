// Rev2D 체크아웃으로 JINY 를 사이트용으로 굳힌다. 아바타를 다시 빌드한 뒤에만 돌리면 된다(결과물은 커밋).
//   node scripts/rev2d/bundle.mjs <Rev2D 폴더> [아바타 폴더 = art/jiny]
// - src/vendor/rev2d-player.js        : Rig + WebGL2 렌더러 번들(player.ts)
// - public/avatars/jiny/jiny.rig.json : 검증·기본값 채움을 마친 모델(브라우저에서 zod 없이 바로 Rig 로), 텍스처 경로는 .webp
// - public/avatars/jiny/textures/     : 모델이 쓰는 텍스처만 WebP 로(PNG 대비 약 1/4)
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';

const [rev2d, avatar = 'art/jiny'] = process.argv.slice(2);
if (!rev2d) throw new Error('usage: node scripts/rev2d/bundle.mjs <Rev2D 폴더> [아바타 폴더]');
const root = path.resolve(rev2d);
const { build } = await import(pathToFileURL(path.join(root, 'node_modules/esbuild/lib/main.js')).href);
const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1'));
const alias = { rev2d: root };
const out = 'public/avatars/jiny';

await build({ entryPoints: [path.join(here, 'player.ts')], bundle: true, format: 'esm', minify: true, target: 'es2022', alias, outfile: 'src/vendor/rev2d-player.js', legalComments: 'none',
  banner: { js: '// Rev2D (MIT, RevStudio) — generated by scripts/rev2d/bundle.mjs, do not edit' } });

const tmp = path.join(root, 'out', 'validate.mjs');
await build({ stdin: { contents: "export { validateModel, formatDiagnostics } from 'rev2d/src/core/validate.js';", resolveDir: root }, bundle: true, platform: 'node', format: 'esm', alias, outfile: tmp });
const { validateModel, formatDiagnostics } = await import(pathToFileURL(tmp).href);
const r = validateModel(JSON.parse(fs.readFileSync(path.join(avatar, 'jiny.r2d.json'), 'utf8')));
if (!r.model) throw new Error(formatDiagnostics(r.diagnostics));

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'textures'), { recursive: true });
for (const t of r.model.textures) {
  const webp = t.path.replace(/\.png$/, '.webp');
  await sharp(path.join(avatar, t.path)).webp({ quality: 95, alphaQuality: 100, effort: 6 }).toFile(path.join(out, webp));
  t.path = webp;
}
fs.writeFileSync(path.join(out, 'jiny.rig.json'), JSON.stringify(r.model));
// WebGL2 가 없을 때·로딩 전 정지 그림
await sharp(path.join(avatar, 'source.png')).resize(640).webp({ quality: 88, alphaQuality: 100 }).toFile(path.join(out, 'still.webp'));
console.log(`ok: src/vendor/rev2d-player.js, ${out}/ (${r.model.textures.length} textures)`);
